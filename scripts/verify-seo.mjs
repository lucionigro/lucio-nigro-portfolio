import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const base = process.argv[2] || 'http://127.0.0.1:5190';
const results = [];
const check = (name, value) => { assert.ok(value, name); results.push(name); };
const response = await fetch(base);
check('Homepage HTTP 200', response.status === 200);
const html = await response.text();
const match = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
check('JSON-LD is server rendered', match);
const schema = JSON.parse(match[1]);
const graph = schema['@graph'];
const person = graph.find(n => n['@type'] === 'Person');
const profile = graph.find(n => n['@type'] === 'ProfilePage');
const website = graph.find(n => n['@type'] === 'WebSite');
check('Person, ProfilePage and WebSite exist', person && profile && website);
check('Real public identity', person.name === 'Lucio Nigro' && person.email === 'lucionigrot@gmail.com');
check('Role and employer match visible SSR content', html.includes(person.jobTitle) && html.includes(person.worksFor.name));
check('Public profiles match page links', person.sameAs.every(url => html.includes(url)));
const ids = new Set(graph.map(n => n['@id']));
function refs(value) {
  if (!value || typeof value !== 'object') return;
  if (value['@id']) check(`Resolved graph ID ${value['@id']}`, ids.has(value['@id']));
  Object.values(value).forEach(refs);
}
refs(graph);
check('ProfilePage mainEntity is this person', profile.mainEntity['@id'] === person['@id']);
check('Canonical uses production domain', new URL(html.match(/<link rel="canonical" href="([^"]+)/)[1]).href === 'https://www.lucionigro.com/');
check('Default document language is English', html.includes('<html lang="en"'));
check('Title identifies Lucio', /<title>Lucio Nigro/.test(html));
check('One primary heading in SSR', (html.match(/<h1\b/g) || []).length === 1);
check('Description and social metadata present', html.includes('name="description"') && html.includes('property="og:image"') && html.includes('name="twitter:card"'));
const robots = await fetch(`${base}/robots.txt`);
check('Robots serves canonical sitemap', robots.ok && (await robots.text()).includes('Sitemap: https://www.lucionigro.com/sitemap.xml'));
const sitemap = await fetch(`${base}/sitemap.xml`);
check('Sitemap serves real canonical homepage', sitemap.ok && (await sitemap.text()).includes('<loc>https://www.lucionigro.com/</loc>'));
const paths = ['/work', '/about', '/photography'];
const canonicalUrls = new Set(['https://www.lucionigro.com/']);
for (const path of paths) {
  const pageResponse = await fetch(`${base}${path}`);
  check(`${path} HTTP 200`, pageResponse.status === 200);
  const source = await pageResponse.text();
  const canonical = new URL(source.match(/<link rel="canonical" href="([^"]+)/)[1]).href;
  check(`${path} own canonical`, canonical === `https://www.lucionigro.com${path}`);
  canonicalUrls.add(canonical);
  check(`${path} default English`, source.includes('<html lang="en"'));
  check(`${path} one h1`, (source.match(/<h1\b/g) || []).length === 1);
  check(`${path} server description and social card`, source.includes('name="description"') && source.includes('property="og:url"') && source.includes('name="twitter:card"'));
  const data = JSON.parse(source.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
  const node = data['@graph'].find(node => node.url === canonical && node['@type'] !== 'Person' && node['@type'] !== 'WebSite');
  check(`${path} SSR schema matches route`, node && node['@id'] === `${canonical}#page`);
  if (path === '/work') check('All three real employers visible', ['Belong', 'Banco Hipotecario', 'QServices'].every(name => source.includes(name)));
  if (path === '/photography') check('Six photographs in collection schema', node.hasPart?.length === 6 && node.hasPart.every(photo => photo['@type'] === 'ImageObject'));
}
check('Four distinct canonical destinations', canonicalUrls.size === 4);
const sitemapSource = await (await fetch(`${base}/sitemap.xml`)).text();
check('Sitemap covers all four real routes', [...canonicalUrls].every(url => sitemapSource.includes(`<loc>${url}</loc>`)));
check('One global menu with three destinations', /<nav aria-label="Main navigation">[\s\S]*?href="\/work"[\s\S]*?href="\/about"[\s\S]*?href="\/photography"[\s\S]*?<\/nav>/.test(html));
check('Room object links go directly to content', ['/work', '/photography', '/about#cinema', '/about#music', '/about#books'].every(path => html.includes(`href="${path}"`)));
await writeFile('seo-schema.json', JSON.stringify(schema, null, 2)+'\n');
await writeFile('seo-validation.json', JSON.stringify({base, checks:results, passed:results.length, limitation:'Local SSR validation; indexing and rich-result display require publication and Google processing.'},null,2)+'\n');
console.log(`${results.length} SEO checks passed against ${base}`);
